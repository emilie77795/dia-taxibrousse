// Initialisation globale avec persistance
const langueStockee = (typeof window !== 'undefined' ? localStorage.getItem('dia_langue') : 'fr') || 'fr'
export const langueCourante = ref(langueStockee === 'en' ? 'en' : 'fr')

export function changerLangue(langue) {
  const nouvelle = langue === 'en' ? 'en' : 'fr'
  langueCourante.value = nouvelle
  try {
    localStorage.setItem('dia_langue', nouvelle)
  } catch (e) {}

  if (typeof document !== 'undefined') {
    document.documentElement.lang = nouvelle
  }

  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('dia:langue-change', { detail: nouvelle }))
  }
}

export function t(cle) {
  const dictionnaire = traductions[langueCourante.value] || traductions.fr
  return dictionnaire[cle] ?? traductions.fr[cle] ?? cle
}

export default {
  install(app) {
    app.config.globalProperties.$t = t
    app.config.globalProperties.$langue = langueCourante
    app.provide('i18n', { t, langueCourante, changerLangue })
  }
}
